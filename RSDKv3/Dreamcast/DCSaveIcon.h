// VMU icons for the RSDKv3 Dreamcast port.
//
// Generated from the artwork pack. Regenerate from the source images rather
// than hand-editing the hex below.
//
//   DC_SAVE_ICON_PAL / DC_SAVE_ICON_DATA   (from color.bmp)
//     The BIOS icon for the save files, shown in the Dreamcast file manager.
//     32x32, 4bpp, two pixels per byte with the LOW nibble holding the LEFT
//     pixel, plus a 16-entry ARGB4444 palette. This is the layout dc/vmu_pkg.h
//     expects for vmu_pkg_t::icon_data and ::icon_pal. Index 0 is transparent.
//
//   DC_VMU_LCD_ICON                        (from the 48x32 mono artwork)
//     The image shown on the VMU's own LCD while the game runs. 48x32, 1bpp,
//     row-major from the TOP-LEFT, MSB = leftmost pixel of each byte, a set bit
//     being a dark (lit) pixel. The source is drawn at the screen's native
//     48x32 with the design carried out to both edges, so nothing is centred or
//     padded here — the bitmap is the art, pixel for pixel.
//
//     vmu_draw_lcd_rotated() is the entry point that takes this orientation.
//     vmu_draw_lcd() wants the same bitmap rotated 180 degrees (its first byte
//     is the BOTTOM-RIGHT pixel), which is why DCSave.cpp calls the rotated one.
//
//     ALIGNMENT IS LOAD-BEARING: vmu_draw_lcd_rotated reads this as uint32_t[48]
//     through an assembly routine that works 32 bits at a time, so the array is
//     explicitly 4-byte aligned.
